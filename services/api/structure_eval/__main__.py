"""Score every case and write reports/structure-eval.md.

    uv run --no-sync python -m structure_eval                  # print and rewrite the report
    uv run --no-sync python -m structure_eval --label "step 2"  # also record the totals in the history

The history (reports/structure-eval-history.json) is what shows each step's before/after.
"""

import argparse
import json
from datetime import date
from pathlib import Path

from structure_eval.cases import all_cases
from structure_eval.score import Score, score_case

REPORTS = Path(__file__).resolve().parent.parent / "reports"
HISTORY = REPORTS / "structure-eval-history.json"


def totals(scores: list[Score]) -> dict:
    paragraphs = sum(s.paragraphs_exact for s in scores)
    paragraph_total = sum(s.paragraphs_total for s in scores)
    return {
        "paragraphs_pct": round(100 * paragraphs / max(1, paragraph_total), 1),
        "headings": f"{sum(s.headings_found for s in scores)}/{sum(s.headings_total for s in scores)}",
        "headings_extra": sum(s.headings_extra for s in scores),
        "junk_spoken": sum(s.junk_spoken for s in scores),
        "words_lost": sum(s.words_lost for s in scores),
        "titles_ok": f"{sum(s.title_ok for s in scores)}/{len(scores)}",
        "authors_ok": f"{sum(s.author_ok for s in scores)}/{len(scores)}",
    }


def _yes(ok: bool) -> str:
    return "yes" if ok else "**no**"


def table(scores: list[Score]) -> str:
    rows = ["| Case | Paragraphs exact | Headings found (extra) | Junk spoken | Words lost | Title | Author |",
            "|---|---|---|---|---|---|---|"]
    for s in scores:
        rows.append(f"| `{s.case}`: {s.description} | {s.paragraphs_exact}/{s.paragraphs_total} ({s.paragraph_pct:.0f}%) "
                    f"| {s.headings_found}/{s.headings_total} (+{s.headings_extra}) | {s.junk_spoken} | {s.words_lost} "
                    f"| {_yes(s.title_ok)} | {_yes(s.author_ok)} |")
    t = totals(scores)
    rows.append(f"| **All cases** | **{t['paragraphs_pct']}%** | **{t['headings']} (+{t['headings_extra']})** "
                f"| **{t['junk_spoken']}** | **{t['words_lost']}** | **{t['titles_ok']}** | **{t['authors_ok']}** |")
    return "\n".join(rows)


def history_table(history: list[dict]) -> str:
    rows = ["| Run | Date | Paragraphs exact | Headings (extra) | Junk spoken | Words lost | Titles | Authors |",
            "|---|---|---|---|---|---|---|---|"]
    for h in history:
        rows.append(f"| {h['label']} | {h['date']} | {h['paragraphs_pct']}% | {h['headings']} (+{h['headings_extra']}) "
                    f"| {h['junk_spoken']} | {h['words_lost']} | {h['titles_ok']} | {h['authors_ok']} |")
    return "\n".join(rows)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--label", help="record this run's totals in the history under this name")
    parser.add_argument("--ai", choices=["off", "claude", "gemini"], default="off",
                        help="add the AI second opinion (calls the provider; needs its API key in .env)")
    args = parser.parse_args()

    scores = [score_case(case, args.ai) for case in all_cases()]
    current = table(scores)
    print(current)

    REPORTS.mkdir(exist_ok=True)
    history = json.loads(HISTORY.read_text()) if HISTORY.exists() else []
    if args.label:
        history = [h for h in history if h["label"] != args.label]  # re-running a label replaces it
        history.append({"label": args.label, "date": date.today().isoformat(), **totals(scores)})
        HISTORY.write_text(json.dumps(history, indent=2) + "\n")
    if args.ai != "off":
        return  # the report's "current scores" always show what import does by default (no AI)

    (REPORTS / "structure-eval.md").write_text(
        "# Structure evaluation\n\n"
        "How well import finds chapters, paragraphs and junk, on one synthetic book rendered into six messy "
        "formats (`structure_eval/`). Generated by `uv run --no-sync python -m structure_eval`; don't edit by hand.\n\n"
        f"## Current scores ({date.today().isoformat()})\n\n{current}\n\n"
        "- **Paragraphs exact:** one block per real paragraph, nothing glued on or split off.\n"
        "- **Extra:** blocks wrongly made headings. **Junk spoken:** licence, contents, running headers, "
        "references or page numbers left in the text. **Words lost:** real story words missing.\n\n"
        f"## History\n\n{history_table(history) if history else '_No labelled runs yet._'}\n"
    )


if __name__ == "__main__":
    main()
